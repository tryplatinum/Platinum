// Writes shared/cipPrograms.ts: every bachelor's program title in the college
// directory, by four-digit CIP code, with how many colleges offer it. Run by
// hand after `npm run import:colleges`:
//
//   npm run build:programs
//
// The list is what a student's intended majors (free text) are matched against
// when a college list is drafted (matchMajors in src/lib/collegeBands.ts), and
// what the preferences form searches. It reads the directory with the service
// role and writes nothing to the database.

import { writeFileSync } from 'node:fs'
import { adminClient, requireSettings } from './testAccounts.js'

requireSettings()

const PAGE = 1000
const db = adminClient()
const programs = new Map<string, { title: string; colleges: number }>()

for (let from = 0; ; from += PAGE) {
  const { data, error } = await db
    .from('college_programs')
    .select('cip_code, cip_title')
    .order('unitid')
    .order('cip_code')
    .range(from, from + PAGE - 1)
  if (error) {
    console.error(`Could not read college_programs: ${error.message}`)
    process.exit(1)
  }
  for (const row of data) {
    const seen = programs.get(row.cip_code)
    if (seen) seen.colleges++
    else programs.set(row.cip_code, { title: row.cip_title, colleges: 1 })
  }
  if (data.length < PAGE) break
}

const rows = [...programs.entries()].sort(([a], [b]) => a.localeCompare(b))
const lines = rows.map(([code, p]) => `  [${JSON.stringify(code)}, ${JSON.stringify(p.title)}, ${p.colleges}],`)
const file = `// Generated by scripts/build-cip-programs.ts from the college directory. Do not edit by hand:
// run \`npm run build:programs\` after \`npm run import:colleges\`.
//
// Every bachelor's program in the directory: four-digit CIP code, the Scorecard's
// title, and how many colleges offer it. No imports, so the browser can use it.

export interface CipProgram {
  cipCode: string
  cipTitle: string
  /** How many colleges in the directory offer it. */
  colleges: number
}

const ROWS: [string, string, number][] = [
${lines.join('\n')}
]

export const CIP_PROGRAMS: CipProgram[] = ROWS.map(([cipCode, cipTitle, colleges]) => ({ cipCode, cipTitle, colleges }))
`
writeFileSync(new URL('../shared/cipPrograms.ts', import.meta.url), file)
console.log(`Wrote ${rows.length} programs to shared/cipPrograms.ts`)
