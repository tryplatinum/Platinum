-- Platinum: firms, members, and one table per collection in AppData (src/types.ts).
--
-- Conventions
--   * Every row carries firm_id. Rows that belong to a student also carry
--     student_id, tied to a student OF THE SAME FIRM by a composite foreign key,
--     and are removed with the student.
--   * Real columns for anything filtered, sorted or joined on. jsonb for nested
--     structures the app always reads whole.
--   * Ids are uuids made by the app (crypto.randomUUID), so a row can be shown
--     before the write returns.
--   * seq records insertion order, so lists come back in the order they were built.
--   * Row level security is on for every table. A signed-in user reaches only
--     rows of a firm they belong to. The anon role reaches nothing.

-- ── Helpers ─────────────────────────────────────────────────────────────────

create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end
$$;

-- ── Firms and members ───────────────────────────────────────────────────────

create table public.firms (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(btrim(name)) between 1 and 200),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.firm_members (
  id uuid primary key default gen_random_uuid(),
  firm_id uuid not null references public.firms (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  role text not null check (role in ('owner', 'counselor')),
  display_name text not null check (length(btrim(display_name)) between 1 and 200),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (firm_id, user_id),
  -- One firm per person for now. Drop this when firm switching is built.
  unique (user_id)
);

create index firm_members_firm_id_idx on public.firm_members (firm_id);

-- Membership checks used by every policy. Security definer so the policies on
-- firm_members itself do not recurse; they reveal only a yes/no about the caller.
create function public.is_firm_member(firm uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.firm_members m
    where m.firm_id = firm and m.user_id = (select auth.uid())
  )
$$;

create function public.is_firm_owner(firm uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.firm_members m
    where m.firm_id = firm and m.user_id = (select auth.uid()) and m.role = 'owner'
  )
$$;

-- The only way a firm comes into being: the caller becomes its owner in the
-- same transaction, so no policy has to allow open inserts.
create function public.create_firm(name text, display_name text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller uuid := (select auth.uid());
  new_firm uuid;
begin
  if caller is null then
    raise exception 'Sign in first.' using errcode = '28000';
  end if;
  if exists (select 1 from public.firm_members m where m.user_id = caller) then
    raise exception 'This account already belongs to a firm.' using errcode = '23505';
  end if;

  insert into public.firms (name) values (btrim(create_firm.name)) returning id into new_firm;
  insert into public.firm_members (firm_id, user_id, role, display_name)
  values (new_firm, caller, 'owner', btrim(create_firm.display_name));
  return new_firm;
end
$$;

-- ── Students and families ───────────────────────────────────────────────────

create table public.students (
  id uuid primary key default gen_random_uuid(),
  firm_id uuid not null references public.firms (id) on delete cascade,
  seq bigint generated by default as identity,
  first_name text not null,
  last_name text not null,
  local_name text,
  grad_year integer not null,
  school text not null default '',
  city text not null default '',
  email text,
  phone text,
  preferred_channel text check (preferred_channel in ('email', 'wechat', 'line', 'text')),
  gpa numeric,
  gpa_weighted numeric,
  tests jsonb not null default '{"aps": []}' check (jsonb_typeof(tests) = 'object'),
  majors jsonb not null default '[]' check (jsonb_typeof(majors) = 'array'),
  interests jsonb not null default '[]' check (jsonb_typeof(interests) = 'array'),
  activities jsonb not null default '[]' check (jsonb_typeof(activities) = 'array'),
  counselor_notes text not null default '',
  onboarded_on date not null default current_date,
  report_settings jsonb not null default '{"schedule": "after_meetings", "recipientIds": []}'
    check (jsonb_typeof(report_settings) = 'object'),
  archived boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Target of the composite foreign keys below.
  unique (firm_id, id)
);

create table public.parents (
