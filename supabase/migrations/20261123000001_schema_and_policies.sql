  status text not null check (status in ('todo', 'in_progress', 'done')),
  progress_note text,
  completed_on date,
  completed_by text check (completed_by in ('student', 'parent', 'counselor', 'ai')),
  created_on date not null default current_date,
  source text not null check (source in ('counselor', 'ai_meeting', 'ai_notes')),
  meeting_id uuid references public.meetings (id) on delete set null,
  -- {by, byId, at}. Present on tasks that began as an AI draft.
  approval jsonb,
  expects_document text check (expects_document in ('academic', 'testing', 'application', 'recommendation', 'financial', 'other')),
  attachments jsonb not null default '[]' check (jsonb_typeof(attachments) = 'array'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (firm_id, student_id) references public.students (firm_id, id) on delete cascade
