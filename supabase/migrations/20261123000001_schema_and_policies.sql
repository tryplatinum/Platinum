-- ── Row level security, privileges and triggers ─────────────────────────────

-- Firms: members read, owners rename. Created only through create_firm.
alter table public.firms enable row level security;
create policy firms_select on public.firms for select to authenticated using (public.is_firm_member(id));
create policy firms_update on public.firms for update to authenticated
  using (public.is_firm_owner(id)) with check (public.is_firm_owner(id));

-- Members: readable by the same firm, writable only by an owner.
alter table public.firm_members enable row level security;
create policy firm_members_select on public.firm_members for select to authenticated using (public.is_firm_member(firm_id));
create policy firm_members_insert on public.firm_members for insert to authenticated with check (public.is_firm_owner(firm_id));
create policy firm_members_update on public.firm_members for update to authenticated
  using (public.is_firm_owner(firm_id)) with check (public.is_firm_owner(firm_id));
create policy firm_members_delete on public.firm_members for delete to authenticated using (public.is_firm_owner(firm_id));

-- Every data table gets the same four policies: the row's firm must be the caller's.
do $$
declare
  t text;
begin
  foreach t in array array['students', 'parents', 'meetings', 'tasks', 'colleges', 'documents', 'reports', 'outbox', 'reminder_rules', 'activity']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy %I on public.%I for select to authenticated using (public.is_firm_member(firm_id))', t || '_select', t);
    execute format('create policy %I on public.%I for insert to authenticated with check (public.is_firm_member(firm_id))', t || '_insert', t);
    execute format(
      'create policy %I on public.%I for update to authenticated using (public.is_firm_member(firm_id)) with check (public.is_firm_member(firm_id))',
      t || '_update', t);
    execute format('create policy %I on public.%I for delete to authenticated using (public.is_firm_member(firm_id))', t || '_delete', t);
  end loop;
end
$$;

-- Privileges are stated outright instead of relying on the project's defaults.
-- anon gets nothing at all; authenticated gets table access that the policies then narrow.
do $$
declare
  t text;
begin
  foreach t in array array['firms', 'firm_members', 'students', 'parents', 'meetings', 'tasks', 'colleges', 'documents', 'reports', 'outbox', 'reminder_rules', 'activity']
  loop
    execute format('revoke all on table public.%I from public, anon, authenticated', t);
    execute format('grant all on table public.%I to service_role', t);
    execute format('create trigger set_updated_at before update on public.%I for each row execute function public.set_updated_at()', t);
  end loop;

  foreach t in array array['students', 'parents', 'meetings', 'tasks', 'colleges', 'documents', 'reports', 'outbox', 'reminder_rules', 'activity', 'firm_members']
  loop
    execute format('grant select, insert, update, delete on table public.%I to authenticated', t);
  end loop;
end
$$;

grant select, update on table public.firms to authenticated;

revoke execute on function public.is_firm_member(uuid) from public, anon;
revoke execute on function public.is_firm_owner(uuid) from public, anon;
revoke execute on function public.create_firm(text, text) from public, anon;
revoke execute on function public.set_updated_at() from public, anon, authenticated;
grant execute on function public.is_firm_member(uuid) to authenticated, service_role;
grant execute on function public.is_firm_owner(uuid) to authenticated, service_role;
grant execute on function public.create_firm(text, text) to authenticated;
