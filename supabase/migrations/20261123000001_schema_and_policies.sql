  firm_id uuid not null references public.firms (id) on delete cascade,
  student_id uuid not null,
  seq bigint generated by default as identity,
  name text not null,
  local_name text,
  relationship text not null check (relationship in ('Mother', 'Father', 'Guardian')),
  language text not null check (language in ('en', 'zh-Hans', 'zh-Hant')),
  channel text not null check (channel in ('email', 'wechat', 'line', 'text')),
  phone text,
  email text,
  wechat_id text,
  line_id text,
  is_primary boolean not null default false,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (firm_id, student_id) references public.students (firm_id, id) on delete cascade
);

-- ── Meetings ────────────────────────────────────────────────────────────────

create table public.meetings (
  id uuid primary key default gen_random_uuid(),
  firm_id uuid not null references public.firms (id) on delete cascade,
  student_id uuid not null,
  seq bigint generated by default as identity,
  title text not null,
  date date not null,
  -- 24h local time, "16:00". Text, because the app has no time zone for it.
  time text not null check (time ~ '^[0-2][0-9]:[0-5][0-9]$'),
  duration_min integer not null default 45 check (duration_min > 0),
  location text,
  status text not null check (status in ('scheduled', 'completed')),
  transcript text,
  agenda jsonb check (agenda is null or jsonb_typeof(agenda) = 'array'),
  -- AI brief, AI drafts and the recap, each with its review state and approvals.
  brief jsonb,
  ai jsonb,
  recap jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (firm_id, student_id) references public.students (firm_id, id) on delete cascade
);

-- ── Tasks ───────────────────────────────────────────────────────────────────

create table public.tasks (
  id uuid primary key default gen_random_uuid(),
