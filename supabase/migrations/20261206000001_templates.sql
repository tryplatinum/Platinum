-- Templates: a firm's own reusable material (task plans, messages, handouts),
-- and the drafts a message template makes.
--
-- Additive only. Two new tables, one new nullable column on tasks, and
-- apply_changes restated whole with the two tables added to its upsert list.
-- Nothing is dropped, no existing row is touched, and no existing policy or
-- grant changes.
--
--   * templates: one row a template. `content` is JSON whose shape is checked
--     in the app by shared/templates.ts. A template is archived, never
--     deleted, so there is no delete policy and it is not in apply_changes'
--     delete list: a task made from a template keeps pointing at it.
--   * message_drafts: what a message template makes for one recipient. A
--     draft is not a message. It sits in the Inbox until a counselor approves
--     it, and only then does the app call queue_message, as for every other
--     send. Nothing in this table is read by the dispatcher.
--   * tasks.template_id: which template a task came from, if any.
--
-- Any member of the firm may read, make and edit templates and drafts, the
-- same rule as reminder_rules (firm-wide settings a counselor works with
-- daily). Folders (document_types) are the owner-only precedent; templates
-- are working material, not structure, so they follow reminder_rules.

create table public.templates (
  id uuid primary key default gen_random_uuid(),
  firm_id uuid not null references public.firms (id) on delete cascade,
  seq bigint generated by default as identity,
  kind text not null check (kind in ('task_plan', 'message', 'handout')),
  name text not null check (char_length(btrim(name)) between 1 and 120),
  content jsonb not null check (jsonb_typeof(content) = 'object'),
  archived boolean not null default false,
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (firm_id, id)
);

create index templates_firm_idx on public.templates (firm_id, archived, kind);

create table public.message_drafts (
  id uuid primary key default gen_random_uuid(),
  firm_id uuid not null references public.firms (id) on delete cascade,
  student_id uuid not null,
  seq bigint generated by default as identity,
  template_id uuid,
  -- Drafts made in one go share this, so the Inbox shows them as one group.
  batch_id uuid not null,
  to_kind text not null check (to_kind in ('student', 'parent')),
  -- No foreign key: an approved draft stays in the history after its parent is removed.
  parent_id uuid,
  to_name text not null,
  channel text not null check (channel in ('email', 'wechat', 'line', 'text')),
  language text not null check (language in ('en', 'zh-Hans', 'zh-Hant')),
  -- The outbox kind it is queued as when approved. No new kind exists for templates.
  kind text not null check (kind in ('parent_report', 'weekly_text')),
  subject text,
  body text not null,
  -- True when the template had no body in the recipient's language and the English one was used.
  untranslated boolean not null default false,
  status text not null default 'draft' check (status in ('draft', 'approved', 'discarded')),
  approval jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (firm_id, student_id) references public.students (firm_id, id) on delete cascade,
  foreign key (firm_id, template_id) references public.templates (firm_id, id),
  check ((to_kind = 'parent') = (parent_id is not null)),
  -- A draft cannot be marked approved without a recorded approval.
  check (status <> 'approved' or approval is not null)
);

create index message_drafts_firm_status_idx on public.message_drafts (firm_id, status);

alter table public.tasks add column template_id uuid;
alter table public.tasks add constraint tasks_firm_id_template_id_fkey foreign key (firm_id, template_id) references public.templates (firm_id, id);

do $$
declare
  t text;
begin
  foreach t in array array['templates', 'message_drafts'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy %I on public.%I for select to authenticated using (public.is_firm_member(firm_id))', t || '_select', t);
    execute format('create policy %I on public.%I for insert to authenticated with check (public.is_firm_member(firm_id))', t || '_insert', t);
    execute format('create policy %I on public.%I for update to authenticated using (public.is_firm_member(firm_id)) with check (public.is_firm_member(firm_id))', t || '_update', t);
    execute format('revoke all on table public.%I from public, anon, authenticated', t);
    execute format('grant select, insert, update on table public.%I to authenticated', t);
    execute format('grant all on table public.%I to service_role', t);
    execute format('create trigger set_updated_at before update on public.%I for each row execute function public.set_updated_at()', t);
  end loop;
end
$$;

-- apply_changes from 20261128000001, whole, with `templates` and
-- `message_drafts` added to the upsert list. `templates` comes before `tasks`
-- so a task made from a template can arrive in the same batch. Neither is in
-- the delete list. Nothing was taken out of either list.
create or replace function public.apply_changes(firm uuid, changes jsonb)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  -- Parents before children, so foreign keys hold inside the batch.
  upsert_order constant text[] := array['document_types', 'students', 'parents', 'meetings', 'templates', 'tasks', 'colleges', 'documents', 'reports', 'reminder_rules', 'activity', 'personal_notes', 'weekly_texts', 'college_list_drafts', 'college_list_draft_items', 'message_drafts'];
  -- The log tables (outbox, activity) are never deleted from row by row, and
  -- folders (document_types) are archived, not deleted.
  delete_order constant text[] := array['college_list_draft_items', 'college_list_drafts', 'weekly_texts', 'personal_notes', 'documents', 'reports', 'colleges', 'tasks', 'meetings', 'parents', 'students'];
  t text;
  items jsonb;
  cols text;
  vals text;
  sets text;
  blocked integer := 0;
begin
  if not public.is_firm_member(firm) then
    raise exception 'You are not a member of this firm.' using errcode = '42501';
  end if;

  if (changes -> 'upsert') ? 'outbox' or (changes -> 'delete') ? 'outbox' then
    raise exception 'Messages are queued with queue_message, not saved with other edits.' using errcode = '42501';
  end if;

  -- Deleting a student, or clearing the caseload, takes the student's documents
  -- with it. When any of those is owner-only, only the owner may do it.
  if not public.is_firm_owner(firm) then
    if coalesce((changes ->> 'clear')::boolean, false) then
      blocked := public.owner_only_file_count(firm);
    elsif jsonb_typeof(changes -> 'delete' -> 'students') = 'array' and jsonb_array_length(changes -> 'delete' -> 'students') > 0 then
      blocked := public.owner_only_file_count(
        firm, array(select value::uuid from jsonb_array_elements_text(changes -> 'delete' -> 'students')));
    end if;
    if blocked > 0 then
      raise exception '% in the way: only the firm''s owner can open %, so only the owner can %. Nothing was changed.',
        case blocked when 1 then '1 owner-only file is' else blocked || ' owner-only files are' end,
        case blocked when 1 then 'it' else 'them' end,
        case when coalesce((changes ->> 'clear')::boolean, false) then 'clear the caseload' else 'delete this student' end
        using errcode = '42501';
    end if;
  end if;

  if changes -> 'firm' ? 'name' then
    update public.firms set name = btrim(changes -> 'firm' ->> 'name') where id = firm;
    if not found then
      raise exception 'Only the firm''s owner can rename it.' using errcode = '42501';
    end if;
  end if;
  if changes -> 'firm' ? 'displayName' then
    update public.firm_members set display_name = btrim(changes -> 'firm' ->> 'displayName')
    where firm_id = firm and user_id = (select auth.uid());
    if not found then
      raise exception 'Only the firm''s owner can change member names.' using errcode = '42501';
    end if;
  end if;

  if changes -> 'firm' ? 'weeklyTextDay' then
    update public.firms set weekly_text_day = (changes -> 'firm' ->> 'weeklyTextDay')::smallint where id = firm;
    if not found then
      raise exception 'Only the firm''s owner can change firm settings.' using errcode = '42501';
    end if;
  end if;

  if changes -> 'firm' ? 'sortFilesAutomatically' then
    update public.firms set sort_files_automatically = (changes -> 'firm' ->> 'sortFilesAutomatically')::boolean where id = firm;
    if not found then
      raise exception 'Only the firm''s owner can change firm settings.' using errcode = '42501';
    end if;
  end if;

  if coalesce((changes ->> 'clear')::boolean, false) then
    -- Everything that belongs to a student goes with the student.
    delete from public.students where firm_id = firm;
    delete from public.reminder_rules where firm_id = firm;
  end if;

  foreach t in array upsert_order loop
    items := changes -> 'upsert' -> t;
    continue when items is null or jsonb_typeof(items) <> 'array' or jsonb_array_length(items) = 0;

    select
      string_agg(format('%I', a.attname), ', ' order by a.attnum),
      string_agg(
        case a.attname
          when 'firm_id' then '$2'
          when 'id' then 'coalesce(r.id, gen_random_uuid())'
          else
            case when a.attnotnull and d.adbin is not null
              then format('coalesce(r.%I, %s)', a.attname, pg_catalog.pg_get_expr(d.adbin, d.adrelid))
              else format('r.%I', a.attname)
            end
        end, ', ' order by a.attnum),
      string_agg(format('%I = excluded.%I', a.attname, a.attname), ', ' order by a.attnum)
        filter (where a.attname not in ('id', 'firm_id'))
    into cols, vals, sets
    from pg_catalog.pg_attribute a
    left join pg_catalog.pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
    where a.attrelid = format('public.%I', t)::regclass
      and a.attnum > 0
      and not a.attisdropped
      and a.attname not in ('seq', 'created_at', 'updated_at');

    execute format(
      'insert into public.%1$I (%2$s)
       select %3$s
       from jsonb_array_elements($1) with ordinality as e(value, ord)
       cross join lateral jsonb_populate_record(null::public.%1$I, e.value) as r
       order by e.ord
       on conflict %4$s do update set %5$s',
      t, cols, vals,
      case t when 'reminder_rules' then '(firm_id, rule)' else '(id)' end,
      sets)
    using items, firm;
  end loop;

  foreach t in array delete_order loop
    items := changes -> 'delete' -> t;
    continue when items is null or jsonb_typeof(items) <> 'array' or jsonb_array_length(items) = 0;
    execute format(
      'delete from public.%I where firm_id = $2 and id in (select value::uuid from jsonb_array_elements_text($1))', t)
    using items, firm;
  end loop;
end
$$;
