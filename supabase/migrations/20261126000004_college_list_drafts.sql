-- College list drafts: a proposed list for one student, reviewed by a
-- counselor before any of it reaches the student's list.
--
--   * college_list_drafts        the draft, the preferences it was made with, who approved it
--   * college_list_draft_items   one college per row: its band, the figures and rule behind
--                                the band, and a short reason
--   * add_draft_to_college_list  writes the kept rows into colleges, marks the draft
--                                approved and logs it, in one transaction
--
-- A draft never appears on the student link or in a parent report: neither reads these tables.

create table public.college_list_drafts (
  id uuid primary key default gen_random_uuid(),
  firm_id uuid not null references public.firms (id) on delete cascade,
  student_id uuid not null,
  seq bigint generated by default as identity,
  created_by uuid references auth.users (id) on delete set null,
  preferences jsonb not null default '{}' check (jsonb_typeof(preferences) = 'object'),
  -- The model's one overall note, if it gave one.
  note text,
  -- {model, at}, or how the draft was made when the AI step failed.
  source jsonb,
  status text not null default 'draft' check (status in ('draft', 'approved', 'discarded')),
  approved_by uuid references auth.users (id) on delete set null,
  approved_by_name text,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (firm_id, student_id) references public.students (firm_id, id) on delete cascade,
  unique (firm_id, id),
  -- A draft cannot be marked approved without who and when.
  check (status <> 'approved' or (approved_at is not null and approved_by_name is not null))
);

create table public.college_list_draft_items (
  id uuid primary key default gen_random_uuid(),
  firm_id uuid not null references public.firms (id) on delete cascade,
  draft_id uuid not null,
  unitid integer not null references public.college_directory (unitid),
  fit text not null check (fit in ('Reach', 'Target', 'Likely')),
  -- The figures and the rule used, with data years: computed in code, never by the model.
  fit_basis jsonb not null default '{}' check (jsonb_typeof(fit_basis) = 'object'),
  fit_set_by text not null default 'rule' check (fit_set_by in ('rule', 'counselor')),
  reason text not null default '' check (char_length(reason) <= 600),
  -- False when the reason is the stock "Matches your filters", not the model's.
  ai_explained boolean not null default true,
  kept boolean not null default true,
  position integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (firm_id, draft_id) references public.college_list_drafts (firm_id, id) on delete cascade,
  unique (draft_id, unitid)
);

create index college_list_drafts_firm_student_idx on public.college_list_drafts (firm_id, student_id);
create index college_list_draft_items_draft_idx on public.college_list_draft_items (firm_id, draft_id);

do $$
declare
  t text;
begin
  foreach t in array array['college_list_drafts', 'college_list_draft_items']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy %I on public.%I for select to authenticated using (public.is_firm_member(firm_id))', t || '_select', t);
    execute format('create policy %I on public.%I for insert to authenticated with check (public.is_firm_member(firm_id))', t || '_insert', t);
    execute format(
      'create policy %I on public.%I for update to authenticated using (public.is_firm_member(firm_id)) with check (public.is_firm_member(firm_id))',
      t || '_update', t);
    execute format('create policy %I on public.%I for delete to authenticated using (public.is_firm_member(firm_id))', t || '_delete', t);
    execute format('revoke all on table public.%I from public, anon, authenticated', t);
    execute format('grant select, insert, update, delete on table public.%I to authenticated', t);
    execute format('grant all on table public.%I to service_role', t);
    execute format('create trigger set_updated_at before update on public.%I for each row execute function public.set_updated_at()', t);
  end loop;
end
$$;

-- "Add to list". Runs as the caller, so row level security decides what it can
-- touch. Returns how many colleges were added; ones already on the list
-- (same directory college, or same name) are skipped.
create function public.add_draft_to_college_list(draft uuid)
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  caller uuid := (select auth.uid());
  d public.college_list_drafts%rowtype;
  who text;
  added integer;
begin
  select * into d from public.college_list_drafts x where x.id = add_draft_to_college_list.draft for update;
  if not found then
    raise exception 'That draft was not found.' using errcode = '42501';
  end if;
  if d.status <> 'draft' then
    raise exception 'That draft has already been added or discarded.' using errcode = '22023';
  end if;
  select m.display_name into who from public.firm_members m where m.firm_id = d.firm_id and m.user_id = caller;
  if who is null then
    raise exception 'You are not a member of this firm.' using errcode = '42501';
  end if;

  insert into public.colleges (firm_id, student_id, name, status, fit, note, directory_unitid, fit_reason, fit_set_by)
  select d.firm_id, d.student_id, cd.name, 'considering', i.fit, nullif(btrim(i.reason), ''),
         i.unitid, nullif(i.fit_basis ->> 'summary', ''), i.fit_set_by
  from public.college_list_draft_items i
  join public.college_directory cd on cd.unitid = i.unitid
  where i.draft_id = d.id
    and i.firm_id = d.firm_id
    and i.kept
    and not exists (
      select 1 from public.colleges c
      where c.firm_id = d.firm_id and c.student_id = d.student_id
        and (c.directory_unitid = i.unitid or lower(btrim(c.name)) = lower(btrim(cd.name)))
    )
  order by i.position, i.created_at;
  get diagnostics added = row_count;

  update public.college_list_drafts x
  set status = 'approved', approved_by = caller, approved_by_name = who, approved_at = now()
  where x.id = d.id;

  insert into public.activity (firm_id, student_id, actor, text)
  values (d.firm_id, d.student_id, 'counselor',
          format('%s added %s to the college list from a draft', who,
                 case added when 1 then '1 college' else added || ' colleges' end));
  return added;
end
$$;

revoke execute on function public.add_draft_to_college_list(uuid) from public, anon;
grant execute on function public.add_draft_to_college_list(uuid) to authenticated;
