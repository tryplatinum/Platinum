-- The weekly text: one short text per student per week, drafted for the
-- counselor, who sends it from their own phone.
--
--   * firms.weekly_text_day      which day the week's texts start (0 = Sunday)
--   * students.weekly_text       per-student switch, on by default
--   * weekly_texts               the draft, and whether this week's text was sent or skipped
--   * outbox.note, kind 'weekly_text'   the log entry says how it went out
--   * student_links.token        see the note below

alter table public.firms add column weekly_text_day smallint not null default 0 check (weekly_text_day between 0 and 6);
alter table public.students add column weekly_text boolean not null default true;

alter table public.outbox add column note text;
alter table public.outbox drop constraint outbox_kind_check;
alter table public.outbox add constraint outbox_kind_check
  check (kind in ('parent_report', 'reminder_upcoming', 'reminder_late', 'meeting_recap', 'essay_feedback', 'weekly_text'));

-- A weekly text carries the student's link, so the link has to be readable
-- again after it is created. Until now only the token's hash was kept. From
-- here on the token is kept too, readable by the firm's members under the same
-- row level security as the rest of the student's data. The hash stays and is
-- still what the server looks a link up by. Links made before this have no
-- stored token and keep working; they just cannot be shown again.
alter table public.student_links add column token text check (token is null or token ~ '^[A-Za-z0-9_-]{43}$');

create table public.weekly_texts (
  id uuid primary key default gen_random_uuid(),
  firm_id uuid not null references public.firms (id) on delete cascade,
  student_id uuid not null,
  seq bigint generated by default as identity,
  -- The first day of the week this text belongs to: the firm's weekly text day.
  week_start date not null,
  status text not null check (status in ('draft', 'sent', 'skipped')),
  body text not null default '',
  -- The fact lines the text was built from, computed by the app. Shown beside the draft.
  facts jsonb check (facts is null or jsonb_typeof(facts) = 'array'),
  source jsonb,
  -- {by, byId, at}: the counselor who pressed Copy or Open in Messages.
  approval jsonb,
  sent_via text check (sent_via in ('copy', 'sms')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (firm_id, student_id) references public.students (firm_id, id) on delete cascade,
  unique (firm_id, student_id, week_start),
  -- A text cannot be marked sent without a recorded approval.
  check (status <> 'sent' or approval is not null)
);

create index weekly_texts_firm_student_idx on public.weekly_texts (firm_id, student_id);

alter table public.weekly_texts enable row level security;
create policy weekly_texts_select on public.weekly_texts for select to authenticated using (public.is_firm_member(firm_id));
create policy weekly_texts_insert on public.weekly_texts for insert to authenticated with check (public.is_firm_member(firm_id));
create policy weekly_texts_update on public.weekly_texts for update to authenticated
  using (public.is_firm_member(firm_id)) with check (public.is_firm_member(firm_id));
create policy weekly_texts_delete on public.weekly_texts for delete to authenticated using (public.is_firm_member(firm_id));

revoke all on table public.weekly_texts from public, anon, authenticated;
grant select, insert, update, delete on table public.weekly_texts to authenticated;
grant all on table public.weekly_texts to service_role;

create trigger set_updated_at before update on public.weekly_texts
  for each row execute function public.set_updated_at();

-- apply_changes again. It now knows the new table and the firm's weekly text
-- day, and fills a required column from its default when a payload omits it.

create or replace function public.apply_changes(firm uuid, changes jsonb)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  -- Parents before children, so foreign keys hold inside the batch.
  upsert_order constant text[] := array['students', 'parents', 'meetings', 'tasks', 'colleges', 'documents', 'reports', 'outbox', 'reminder_rules', 'activity', 'weekly_texts'];
  -- The log tables (outbox, activity) are never deleted from row by row.
  delete_order constant text[] := array['weekly_texts', 'documents', 'reports', 'colleges', 'tasks', 'meetings', 'parents', 'students'];
  t text;
  items jsonb;
  cols text;
  vals text;
  sets text;
begin
  if not public.is_firm_member(firm) then
    raise exception 'You are not a member of this firm.' using errcode = '42501';
  end if;

  if changes -> 'firm' ? 'name' then
    update public.firms set name = btrim(changes -> 'firm' ->> 'name') where id = firm;
    if not found then
      raise exception 'Only the firm''s owner can rename it.' using errcode = '42501';
    end if;
  end if;
  if changes -> 'firm' ? 'displayName' then
    update public.firm_members set display_name = btrim(changes -> 'firm' ->> 'displayName')
    where firm_id = firm and user_id = (select auth.uid());
    if not found then
      raise exception 'Only the firm''s owner can change member names.' using errcode = '42501';
    end if;
  end if;

  if changes -> 'firm' ? 'weeklyTextDay' then
    update public.firms set weekly_text_day = (changes -> 'firm' ->> 'weeklyTextDay')::smallint where id = firm;
    if not found then
      raise exception 'Only the firm''s owner can change firm settings.' using errcode = '42501';
    end if;
  end if;

  if coalesce((changes ->> 'clear')::boolean, false) then
    -- Everything that belongs to a student goes with the student.
    delete from public.students where firm_id = firm;
    delete from public.reminder_rules where firm_id = firm;
  end if;

  foreach t in array upsert_order loop
    items := changes -> 'upsert' -> t;
    continue when items is null or jsonb_typeof(items) <> 'array' or jsonb_array_length(items) = 0;

    -- Every column except the ones the database fills in. firm_id always comes
    -- from the argument, never from the payload.
    select
      string_agg(format('%I', a.attname), ', ' order by a.attnum),
      string_agg(
        case a.attname
          when 'firm_id' then '$2'
          when 'id' then 'coalesce(r.id, gen_random_uuid())'
          else
            -- A required column the payload leaves out takes its default, so a
            -- browser still running an older version keeps working after a
            -- column is added.
            case when a.attnotnull and d.adbin is not null
              then format('coalesce(r.%I, %s)', a.attname, pg_catalog.pg_get_expr(d.adbin, d.adrelid))
              else format('r.%I', a.attname)
            end
        end, ', ' order by a.attnum),
      string_agg(format('%I = excluded.%I', a.attname, a.attname), ', ' order by a.attnum)
        filter (where a.attname not in ('id', 'firm_id'))
    into cols, vals, sets
    from pg_catalog.pg_attribute a
    left join pg_catalog.pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
    where a.attrelid = format('public.%I', t)::regclass
      and a.attnum > 0
      and not a.attisdropped
      and a.attname not in ('seq', 'created_at', 'updated_at');

    execute format(
      'insert into public.%1$I (%2$s)
       select %3$s
       from jsonb_array_elements($1) with ordinality as e(value, ord)
       cross join lateral jsonb_populate_record(null::public.%1$I, e.value) as r
       order by e.ord
       on conflict %4$s do update set %5$s',
      t, cols, vals,
      case t when 'reminder_rules' then '(firm_id, rule)' else '(id)' end,
      sets)
    using items, firm;
  end loop;

  foreach t in array delete_order loop
    items := changes -> 'delete' -> t;
    continue when items is null or jsonb_typeof(items) <> 'array' or jsonb_array_length(items) = 0;
    execute format(
      'delete from public.%I where firm_id = $2 and id in (select value::uuid from jsonb_array_elements_text($1))', t)
    using items, firm;
  end loop;
end
$$;

