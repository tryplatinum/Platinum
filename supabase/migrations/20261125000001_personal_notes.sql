-- What the AI knows about each student, and the parent copy setting.
--
--   * personal_notes               small personal details a student mentioned ("regional
--                                  tournament on Saturday"), saved only once a counselor
--                                  approves them. Used in texts to the student. Never in
--                                  anything a parent reads, and never on the student link.
--   * students.parent_copy         when a message to the student also goes to the parent
--   * weekly_texts.used_note       the note a weekly text drew on, shown beside the draft
--   * weekly_texts.parent_copy     the separate short draft to the primary parent
--   * outbox.approval              who approved a logged message, and when

alter table public.students add column parent_copy text not null default 'when_slipping'
  check (parent_copy in ('always', 'when_slipping', 'never'));

create table public.personal_notes (
  id uuid primary key default gen_random_uuid(),
  firm_id uuid not null references public.firms (id) on delete cascade,
  student_id uuid not null,
  seq bigint generated by default as identity,
  text text not null check (btrim(text) <> '' and char_length(text) <= 300),
  -- The day of the event the note is about, when the student gave one.
  event_date date,
  -- 'meeting': suggested by the AI from a meeting's notes and approved. 'counselor': typed in by hand.
  source text not null check (source in ('meeting', 'counselor')),
  meeting_id uuid references public.meetings (id) on delete set null,
  -- {by, byId, at}. A note does not exist until a counselor has approved or written it.
  approval jsonb not null check (approval ? 'by' and approval ? 'at'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (firm_id, student_id) references public.students (firm_id, id) on delete cascade
);

create index personal_notes_firm_student_idx on public.personal_notes (firm_id, student_id);
create index personal_notes_meeting_idx on public.personal_notes (meeting_id) where meeting_id is not null;

alter table public.personal_notes enable row level security;
create policy personal_notes_select on public.personal_notes for select to authenticated using (public.is_firm_member(firm_id));
create policy personal_notes_insert on public.personal_notes for insert to authenticated with check (public.is_firm_member(firm_id));
create policy personal_notes_update on public.personal_notes for update to authenticated
  using (public.is_firm_member(firm_id)) with check (public.is_firm_member(firm_id));
create policy personal_notes_delete on public.personal_notes for delete to authenticated using (public.is_firm_member(firm_id));

revoke all on table public.personal_notes from public, anon, authenticated;
grant select, insert, update, delete on table public.personal_notes to authenticated;
grant all on table public.personal_notes to service_role;

create trigger set_updated_at before update on public.personal_notes
  for each row execute function public.set_updated_at();

-- The note a weekly text used: {id, text}, kept as it read when the text was drafted.
alter table public.weekly_texts add column used_note jsonb;
-- The parent copy: {parentId, taskId, channel, language, kind, body, bodyEn, source, status, approval}.
-- It cannot be marked sent without a recorded approval.
alter table public.weekly_texts add column parent_copy jsonb
  check (parent_copy is null or parent_copy ->> 'status' is distinct from 'sent' or parent_copy ? 'approval');

-- {by, byId, at} on messages a counselor approved. Absent on automatic ones and on older rows.
alter table public.outbox add column approval jsonb;

-- apply_changes again, now knowing personal_notes. Nothing else in it changes.

create or replace function public.apply_changes(firm uuid, changes jsonb)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  -- Parents before children, so foreign keys hold inside the batch.
  upsert_order constant text[] := array['students', 'parents', 'meetings', 'tasks', 'colleges', 'documents', 'reports', 'outbox', 'reminder_rules', 'activity', 'personal_notes', 'weekly_texts'];
  -- The log tables (outbox, activity) are never deleted from row by row.
  delete_order constant text[] := array['weekly_texts', 'personal_notes', 'documents', 'reports', 'colleges', 'tasks', 'meetings', 'parents', 'students'];
  t text;
  items jsonb;
  cols text;
  vals text;
  sets text;
begin
  if not public.is_firm_member(firm) then
    raise exception 'You are not a member of this firm.' using errcode = '42501';
  end if;

  if changes -> 'firm' ? 'name' then
    update public.firms set name = btrim(changes -> 'firm' ->> 'name') where id = firm;
    if not found then
      raise exception 'Only the firm''s owner can rename it.' using errcode = '42501';
    end if;
  end if;
  if changes -> 'firm' ? 'displayName' then
    update public.firm_members set display_name = btrim(changes -> 'firm' ->> 'displayName')
    where firm_id = firm and user_id = (select auth.uid());
    if not found then
      raise exception 'Only the firm''s owner can change member names.' using errcode = '42501';
    end if;
  end if;

  if changes -> 'firm' ? 'weeklyTextDay' then
    update public.firms set weekly_text_day = (changes -> 'firm' ->> 'weeklyTextDay')::smallint where id = firm;
    if not found then
      raise exception 'Only the firm''s owner can change firm settings.' using errcode = '42501';
    end if;
  end if;

  if coalesce((changes ->> 'clear')::boolean, false) then
    -- Everything that belongs to a student goes with the student.
    delete from public.students where firm_id = firm;
    delete from public.reminder_rules where firm_id = firm;
  end if;

  foreach t in array upsert_order loop
    items := changes -> 'upsert' -> t;
    continue when items is null or jsonb_typeof(items) <> 'array' or jsonb_array_length(items) = 0;

    -- Every column except the ones the database fills in. firm_id always comes
    -- from the argument, never from the payload.
    select
      string_agg(format('%I', a.attname), ', ' order by a.attnum),
      string_agg(
        case a.attname
          when 'firm_id' then '$2'
          when 'id' then 'coalesce(r.id, gen_random_uuid())'
          else
            -- A required column the payload leaves out takes its default, so a
            -- browser still running an older version keeps working after a
            -- column is added.
            case when a.attnotnull and d.adbin is not null
              then format('coalesce(r.%I, %s)', a.attname, pg_catalog.pg_get_expr(d.adbin, d.adrelid))
              else format('r.%I', a.attname)
            end
        end, ', ' order by a.attnum),
      string_agg(format('%I = excluded.%I', a.attname, a.attname), ', ' order by a.attnum)
        filter (where a.attname not in ('id', 'firm_id'))
    into cols, vals, sets
    from pg_catalog.pg_attribute a
    left join pg_catalog.pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
    where a.attrelid = format('public.%I', t)::regclass
      and a.attnum > 0
      and not a.attisdropped
      and a.attname not in ('seq', 'created_at', 'updated_at');

    execute format(
      'insert into public.%1$I (%2$s)
       select %3$s
       from jsonb_array_elements($1) with ordinality as e(value, ord)
       cross join lateral jsonb_populate_record(null::public.%1$I, e.value) as r
       order by e.ord
       on conflict %4$s do update set %5$s',
      t, cols, vals,
      case t when 'reminder_rules' then '(firm_id, rule)' else '(id)' end,
      sets)
    using items, firm;
  end loop;

  foreach t in array delete_order loop
    items := changes -> 'delete' -> t;
    continue when items is null or jsonb_typeof(items) <> 'array' or jsonb_array_length(items) = 0;
    execute format(
      'delete from public.%I where firm_id = $2 and id in (select value::uuid from jsonb_array_elements_text($1))', t)
    using items, firm;
  end loop;
end
$$;
